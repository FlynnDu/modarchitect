def protect_research_rows() -> None:
    """补齐元数据比较未表达的租户策略与不可变触发器。"""
    scope = (
        "company_source = current_setting('modarchitect.company_source', true) "
        "AND company_id::text = current_setting('modarchitect.company_id', true)"
    )
    design = (
        "subject = current_setting('modarchitect.subject', true) "
        "AND resource_scope_id IN (SELECT resource_scope_id FROM public.resource_scopes)"
    )
    owner = "design_id IN (SELECT design_id FROM public.research_designs)"
    policies = {
        "resource_scopes": scope,
        "research_designs": design,
        "research_design_drafts": owner,
        "research_design_versions": owner,
        "research_design_components": (
            "design_version_id IN (SELECT design_version_id FROM public.research_design_versions)"
        ),
    }
    for table, condition in policies.items():
        op.execute("ALTER TABLE public.%s ENABLE ROW LEVEL SECURITY" % table)
        op.execute("ALTER TABLE public.%s FORCE ROW LEVEL SECURITY" % table)
        op.execute(
            "CREATE POLICY ownership ON public.%s USING (%s)" % (table, condition)
        )
    op.execute("""
        CREATE FUNCTION public.reject_frozen_research_change() RETURNS trigger
        LANGUAGE plpgsql SET search_path = pg_catalog AS $$
        BEGIN
            RAISE EXCEPTION 'Frozen research evidence cannot be changed';
        END;
        $$
    """)
    for table in (
        "model_component_definitions",
        "research_design_versions",
        "research_design_components",
    ):
        op.execute(
            "CREATE TRIGGER immutable_research BEFORE UPDATE OR DELETE ON public.%s "
            "FOR EACH ROW EXECUTE FUNCTION public.reject_frozen_research_change()"
            % table
        )


def seed_catalog() -> None:
    """只在首版迁移中登记其冻结目录制品。"""
    table = sa.table(
        "model_component_definitions",
        sa.column("definition_id", sa.Uuid()),
        sa.column("code", sa.String()),
        sa.column("revision", sa.Integer()),
        sa.column("contract_json", sa.JSON()),
        sa.column("contract_sha256", sa.String()),
    )
    rows = [
        {
            "definition_id": new_uuid7(),
            "code": item["code"],
            "revision": item["revision"],
            "contract_json": item,
            "contract_sha256": identity_sha256(item),
        }
        for item in frozen_contracts()
    ]
    op.bulk_insert(table, rows)


